export function findKrTicker(name: string): string | null {
  const q = name.trim().replace(/\s+/g, '').toLowerCase()

  // 1. 정확히 일치
  for (const [n, code, mkt] of KR_LIST) {
    if (n.replace(/\s+/g, '').toLowerCase() === q) return `${code}.${mkt}`
  }

  // 2. 입력이 종목명으로 시작 or 종목명이 입력으로 시작
  for (const [n, code, mkt] of KR_LIST) {
    const normalized = n.replace(/\s+/g, '').toLowerCase()
    if (normalized.startsWith(q) || q.startsWith(normalized)) return `${code}.${mkt}`
  }

  // 3. 포함 관계
  for (const [n, code, mkt] of KR_LIST) {
    if (n.replace(/\s+/g, '').toLowerCase().includes(q)) return `${code}.${mkt}`
  }

  return null
}
